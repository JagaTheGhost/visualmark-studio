/**
 * Visual PDF Export Utility for README Studio
 * Converts the rendered markdown preview (including formatted headings, tables,
 * syntax-highlighted code blocks, Mermaid diagrams, and badges) directly into
 * an actual downloadable .pdf file without opening browser print mode.
 */

export async function exportToPdf({
  title = 'README',
  contentElement = null,
  rawMarkdown = '',
  themeMode = 'dark'
}) {
  const [{ jsPDF }, { default: html2canvas }] = await Promise.all([
    import('jspdf'),
    import('html2canvas')
  ])
  const isDark = themeMode !== 'light'
  const bgColor = themeMode === 'light' ? '#ffffff' : themeMode === 'slate' ? '#0f172a' : '#0d1117'
  const textColor = themeMode === 'light' ? '#1f2328' : '#e6edf3'

  // Prepare off-screen container with standardized desktop width (860px)
  // so the output PDF is consistent, gorgeous, and not dependent on current pane width
  const wrapper = document.createElement('div')
  wrapper.style.position = 'fixed'
  wrapper.style.left = '-9999px'
  wrapper.style.top = '0'
  wrapper.style.width = '860px'
  wrapper.style.padding = '32px'
  wrapper.style.boxSizing = 'border-box'
  wrapper.style.backgroundColor = bgColor
  wrapper.style.color = textColor
  wrapper.style.fontFamily = '-apple-system, BlinkMacSystemFont, "Segoe UI", "Noto Sans", Helvetica, Arial, sans-serif'
  wrapper.style.fontSize = '14px'
  wrapper.style.lineHeight = '1.6'
  wrapper.style.zIndex = '-99999'
  wrapper.className = `markdown-body theme-${themeMode}`

  // Add document header watermark/banner inside the exported PDF
  const headerBanner = document.createElement('div')
  headerBanner.style.display = 'flex'
  headerBanner.style.justifyContent = 'space-between'
  headerBanner.style.alignItems = 'center'
  headerBanner.style.borderBottom = `1px solid ${isDark ? '#30363d' : '#d0d7de'}`
  headerBanner.style.paddingBottom = '10px'
  headerBanner.style.marginBottom = '24px'
  headerBanner.style.fontSize = '12px'
  headerBanner.style.color = isDark ? '#8b949e' : '#57606a'

  const dateStr = new Date().toLocaleDateString(undefined, {
    year: 'numeric',
    month: 'short',
    day: 'numeric'
  })
  headerBanner.innerHTML = `
    <span style="font-weight: 700; color: #58a6ff; letter-spacing: 0.05em; text-transform: uppercase;">VisualMark Studio</span>
    <span style="font-weight: 600; color: ${textColor};">${title}.md</span>
    <span>${dateStr}</span>
  `
  wrapper.appendChild(headerBanner)

  if (contentElement) {
    const clone = contentElement.cloneNode(true)

    // Strip interactive buttons like code copy button
    const removeSelectors = ['.code-copy-btn', '.icon-copy-btn', 'button']
    removeSelectors.forEach((sel) => {
      clone.querySelectorAll(sel).forEach((el) => el.remove())
    })

    // Ensure all SVGs (e.g. Mermaid charts) retain their display attributes
    clone.querySelectorAll('svg').forEach((svg) => {
      svg.style.maxWidth = '100%'
      svg.style.height = 'auto'
      svg.style.display = 'block'
      svg.style.margin = '10px auto'
    })

    wrapper.appendChild(clone)
  } else if (rawMarkdown) {
    const fallback = document.createElement('pre')
    fallback.style.whiteSpace = 'pre-wrap'
    fallback.style.fontFamily = 'monospace'
    fallback.textContent = rawMarkdown
    wrapper.appendChild(fallback)
  }

  // Footer banner
  const footerBanner = document.createElement('div')
  footerBanner.style.borderTop = `1px solid ${isDark ? '#30363d' : '#d0d7de'}`
  footerBanner.style.paddingTop = '12px'
  footerBanner.style.marginTop = '32px'
  footerBanner.style.fontSize = '11px'
  footerBanner.style.color = isDark ? '#8b949e' : '#6e7781'
  footerBanner.style.display = 'flex'
  footerBanner.style.justifyContent = 'space-between'
  footerBanner.innerHTML = `
    <span>Generated by VisualMark Studio</span>
    <span>${title}.md</span>
  `
  wrapper.appendChild(footerBanner)

  document.body.appendChild(wrapper)

  try {
    // Wait briefly for layout and SVG rendering to settle
    await new Promise((resolve) => setTimeout(resolve, 150))

    // Dynamically cap scale to avoid exceeding browser maximum 2D canvas limits on long documents
    const elementHeight = wrapper.offsetHeight || 1000
    const scaleFactor = elementHeight > 8000 ? 1.25 : elementHeight > 4500 ? 1.5 : 2.0

    // Capture visual layout for crisp high-DPI text and graphics
    const canvas = await html2canvas(wrapper, {
      scale: scaleFactor,
      useCORS: true,
      allowTaint: true,
      logging: false,
      backgroundColor: bgColor,
      scrollX: 0,
      scrollY: 0,
      windowWidth: 860
    })

    if (!canvas || canvas.width <= 0 || canvas.height <= 0) {
      throw new Error('Unable to render preview canvas for PDF generation.')
    }

    // Page dimensions in mm for standard A4
    const pdf = new jsPDF('p', 'mm', 'a4')
    const pageWidth = pdf.internal.pageSize.getWidth() // 210 mm
    const pageHeight = pdf.internal.pageSize.getHeight() // 297 mm
    const margin = 10 // 10 mm margin
    const contentWidth = pageWidth - margin * 2 // 190 mm
    const maxPageContentHeight = pageHeight - margin * 2 // 277 mm

    // Pixels per mm based on the rendered canvas
    const pxPerMm = canvas.width / contentWidth
    const sliceHeightPx = Math.max(10, Math.floor(maxPageContentHeight * pxPerMm))

    let currentY = 0
    let pageIndex = 0

    // Slice canvas cleanly across pages so no text distortion or negative coordinate artifacts occur
    while (currentY < canvas.height) {
      const remainingHeightPx = canvas.height - currentY
      const thisSliceHeightPx = Math.min(sliceHeightPx, remainingHeightPx)
      if (thisSliceHeightPx <= 0) break

      const sliceCanvas = document.createElement('canvas')
      sliceCanvas.width = canvas.width
      sliceCanvas.height = thisSliceHeightPx
      const sliceCtx = sliceCanvas.getContext('2d')

      sliceCtx.fillStyle = bgColor
      sliceCtx.fillRect(0, 0, sliceCanvas.width, sliceCanvas.height)
      sliceCtx.drawImage(
        canvas,
        0,
        currentY,
        canvas.width,
        thisSliceHeightPx,
        0,
        0,
        canvas.width,
        thisSliceHeightPx
      )

      const sliceMmHeight = (thisSliceHeightPx * contentWidth) / canvas.width
      const imgData = sliceCanvas.toDataURL('image/jpeg', 0.95)

      if (pageIndex > 0) {
        pdf.addPage()
      }

      pdf.addImage(imgData, 'JPEG', margin, margin, contentWidth, sliceMmHeight)

      currentY += thisSliceHeightPx
      pageIndex++
    }

    // Native desktop save dialog or browser download fallback
    if (typeof window !== 'undefined' && window.electronAPI?.saveBinaryDialog) {
      const arrayBuffer = pdf.output('arraybuffer')
      const bytes = new Uint8Array(arrayBuffer)
      let binary = ''
      const len = bytes.byteLength
      for (let i = 0; i < len; i++) {
        binary += String.fromCharCode(bytes[i])
      }
      const base64Data = window.btoa(binary)
      const res = await window.electronAPI.saveBinaryDialog({
        defaultPath: `${title}.pdf`,
        filters: [{ name: 'PDF Document', extensions: ['pdf'] }, { name: 'All Files', extensions: ['*'] }],
        base64Data
      })
      return !res.canceled
    } else {
      pdf.save(`${title}.pdf`)
      return true
    }
  } finally {
    if (document.body.contains(wrapper)) {
      document.body.removeChild(wrapper)
    }
  }
}
